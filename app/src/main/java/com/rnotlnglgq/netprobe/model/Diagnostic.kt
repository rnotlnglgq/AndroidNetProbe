    fun legacy(code: String, vararg args: Any?): String = String.format(java.util.Locale.ROOT, requireNotNull(templates[code]), *args)
    private val rules = templates.map { (code, text) ->
        val pieces = text.split(Regex("%[0-9]+" + Regex.escape("$" + "s")))
        code to Regex(pieces.joinToString("(.*?)") { Regex.escape(it) })
    }
    fun fromLegacy(text: String): Diagnostic? = rules.firstNotNullOfOrNull { (code, pattern) ->
        pattern.matchEntire(text)?.let { Diagnostic(code,it.groupValues.drop(1)) }
    }
